export function getLearningTopicQuestions(topic: LearningTopic, kind: "basics" | "sales") {
  const questions = kind === "basics" ? topic.basicsQuestions : topic.salesQuestions;
  return questions.map(([question, answer, firstAlternative, secondAlternative], index) => {
    const correctIndex = index % 3;
    const options = [firstAlternative, secondAlternative];
    options.splice(correctIndex, 0, answer);
    return { question, type: "SINGLE" as const, options, correctAnswer: { index: correctIndex }, sortOrder: index + 1 };
  });
}

export function getLearningTopicForCategory(brand: string, category: string) {
  return learningTopics.find((topic) => topic.brand === brand && topic.category === category);
}
